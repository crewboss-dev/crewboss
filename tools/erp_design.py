"""The ported design layer: page-level CSS copied from the upstream design system (the ERP's base.html <style> block) into
app/static/css/erp-design.css, section by section. chrome.css and theme-tokens.css are whole-file copies (tests/test_chrome_drift.py);
this is the same idea for the parts that upstream keeps inline: the page shell, record head and pills, list filters and rows,
the master-detail pane, press states and menu motion, the phone avatar popover, sheets.

  python -m tools.erp_design <upstream base.html>      regenerate app/static/css/erp-design.css from the upstream
  tests/test_design_drift.py                           checks the committed file against the upstream (skipped unless the
                                                       upstream path is set, like the chrome guard)

A section = the upstream lines from a START line (matched by its text, after the optional `after` marker) up to, not
including, the first later line that begins with END. Comments are dropped (they are upstream's notes, not code); the
comparison ignores comments, blank lines and indentation, so only a real rule change counts as drift.
Dead selectors for upstream-only pages (a table's data attributes, a detail pane's old name) are kept: they match nothing
here, and keeping them is what makes the copy verbatim."""
from __future__ import annotations

import re
import sys
from pathlib import Path

# (name, after-marker or None, START text, END text)
SECTIONS = [
    ("shell", None, "html, body{ height:100%; }", "/* ---- Attachments"),
    ("table-base", None, ".dt-scroll{", "/* Master-detail (Cases)"),
    ("record-head", None, ".hub-head{ padding:12px 14px;", ".fav-star{"),
    ("record-title-and-pills", None, ".hub-head-main{", "/* Full-screen mobile area menu"),
    ("record-body", None, ".hub-body{ padding:12px 14px; }", "/* Mobile filter bar"),
    ("list-filters", None, ".mfilter{", "/* NEW on a Now card"),
    ("segmented", None, ".mseg{ display:inline-flex;", "/* The Now slice picker"),
    ("filter-chips", None, ".mseg-group{", "@media (min-width:768px){"),
    ("master-detail", "more pills off-screen", "@media (min-width:768px){", "/* ── Control sizes"),
    ("control-sizes", None, ".pill-sm, .pill-lg, .pill-field{", "[data-add-body]"),
    ("list-rows", "[data-add-body] > form", "@media (max-width:767px){", "/* 2-line rows"),
    ("press-states", None, "button:active{ transform:scale(.97);", "/* ---- §7"),
    ("menu-motion", None, "#nav-more-menu:not(.hidden), #user-menu:not(.hidden)", "/* ---- §12"),
    ("avatar-popover", None, "#me-pop{ position:fixed;", "/* THE THEME PILL"),
    ("record-head-blur", "The sticky hub head gets the same treatment", ".hub-head{", "/* Declared at the TOP LEVEL"),
    ("skeleton-and-fade", None, ".skel{ position:relative;", "/* Swapping a hub tab"),
    ("sheet-handle", None, ".sheet-grab{", "/* A job settling"),
]

MARK = "/* @@ {name} */"
_COMMENT = re.compile(r"/\*.*?\*/", re.S)


def style_block(base_html: str) -> list[str]:
    """The upstream page's first <style> block, as lines."""
    m = re.search(r"<style>(.*?)</style>", base_html, re.S)
    if not m:
        raise ValueError("no <style> block in the upstream base.html")
    return m.group(1).splitlines()


def section_lines(lines: list[str], after: str | None, start: str, end: str) -> list[str]:
    i = 0
    if after:
        i = next(n for n, l in enumerate(lines) if after in l)
    s = next(n for n in range(i, len(lines)) if lines[n].strip().startswith(start))
    # the end marker is searched from the line after START, except where START itself opens a block that END also opens
    e = next((n for n in range(s + 1, len(lines)) if lines[n].strip().startswith(end)), len(lines))
    return lines[s:e]


def normalise(text: str) -> list[str]:
    """Comments, blank lines and indentation removed: what is left is the rules."""
    out = []
    for l in _COMMENT.sub("", text).splitlines():
        l = l.strip()
        if l:
            out.append(l)
    return out


def build(base_html: str) -> str:
    lines = style_block(base_html)
    parts = ["/* The ported design layer: GENERATED by tools/erp_design.py from the upstream design system's page styles; do not edit by hand.\n"
             "   Crewboss-only rules live in css/shell.css. tests/test_design_drift.py guards this file against the upstream. */"]
    for name, after, start, end in SECTIONS:
        body = _COMMENT.sub("", "\n".join(section_lines(lines, after, start, end)))
        body = "\n".join(l.rstrip() for l in body.splitlines() if l.strip())
        parts.append(MARK.format(name=name) + "\n" + body)
    return "\n".join(parts) + "\n"


def parse(css: str) -> dict[str, list[str]]:
    """{section name: normalised rule lines} of a generated file."""
    out: dict[str, list[str]] = {}
    name = None
    for chunk in re.split(r"(/\* @@ [\w-]+ \*/)", css):
        m = re.fullmatch(r"/\* @@ ([\w-]+) \*/", chunk.strip())
        if m:
            name = m.group(1)
        elif name:
            out[name] = normalise(chunk)
    return out


def upstream_sections(base_html: str) -> dict[str, list[str]]:
    lines = style_block(base_html)
    return {name: normalise("\n".join(section_lines(lines, after, start, end))) for name, after, start, end in SECTIONS}


if __name__ == "__main__":
    src = Path(sys.argv[1])
    dest = Path(__file__).resolve().parent.parent / "app" / "static" / "css" / "erp-design.css"
    dest.write_text(build(src.read_text()))
    print("wrote", dest)
